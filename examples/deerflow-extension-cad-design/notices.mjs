// Preserve upstream license texts for the locked production dependency tree.
import { readdir, readFile, writeFile } from "node:fs/promises";

const lock = JSON.parse(await readFile("package-lock.json", "utf8"));
// Indent quoted upstream text so README underlines cannot resemble merge markers.
const quoteNotice = (body) =>
  body
    .trim()
    .split(/\r?\n/)
    .map((line) => (line.trimEnd() ? `    ${line.trimEnd()}` : ""))
    .join("\n");

let output = `# Third-party notices

The CAD design page is implemented for DeerFlow. Its browser bundle includes
three.js (the WebGL renderer and OrbitControls). The STL reader and the mesh
preparation are the CAD preview extension's own code
(\`../deerflow-extension-cad-preview/ui\`), shared by relative import.

Generated by \`node notices.mjs\` from \`package-lock.json\` and installed packages.

`;
for (const [directory, entry] of Object.entries(lock.packages).sort(
  ([a], [b]) => a.localeCompare(b),
)) {
  if (!directory || entry.dev) continue;
  const pkg = JSON.parse(await readFile(`${directory}/package.json`, "utf8"));
  const files = (await readdir(directory)).filter((name) =>
    /^(licen[sc]e|copying|notice)([.-]|$)/i.test(name),
  );
  if (!files.length) throw new Error(`Missing license notice: ${directory}`);
  output += `## ${pkg.name} ${pkg.version}\n\nLicense: ${pkg.license ?? entry.license}.\n\n`;
  for (const name of files.sort()) {
    const body = await readFile(`${directory}/${name}`, "utf8");
    output += `### ${name}\n\n${quoteNotice(body)}\n\n`;
  }
}
await writeFile("THIRD_PARTY_NOTICES.md", output.trimEnd() + "\n", "utf8");
