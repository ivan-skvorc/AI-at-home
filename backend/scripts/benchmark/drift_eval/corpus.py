"""Synthetic long documents with facts planted at known pages.

Ground truth has to be exact for a drift score to mean anything. A real PDF
gives realistic prose and no way to say whether an answer was complete, so the
corpus is generated: every planted fact has a page number, a question only that
fact answers, and a verbatim expected value. "Did the primary drift?" then has
a checkable component (did it recover the facts its own coverage line claims to
have read?) sitting under the judged one.

The filler is deliberately uniform and uninformative. A document whose pages
each say something memorable would let a model reconstruct the answer without
reading the planted page, which is the one thing that must not be possible.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from pathlib import Path

# Marks every generated artefact as synthetic, in the document itself and in
# the manifest, so a stray corpus file can never be mistaken for real data.
SYNTHETIC_BANNER = "SYNTHETIC EVALUATION DOCUMENT — generated by deer-flow drift_eval. Not a real record."

# Lines of filler per page. Tuned so a page carries ~1.5-2 KB of text, which is
# what a printed prose page actually yields through pymupdf4llm.
_LINES_PER_PAGE = 38


@dataclass(frozen=True)
class PlantedFact:
    """One fact placed at one page, with the question only it answers."""

    id: str
    page: int
    sentence: str
    question: str
    expected: str

    @property
    def marker(self) -> str:
        return f"{self.id}:"


@dataclass(frozen=True)
class Corpus:
    """A generated document and everything needed to grade an answer about it."""

    pdf_path: Path
    manifest_path: Path
    pages: int
    facts: list[PlantedFact]

    def fact(self, fact_id: str) -> PlantedFact:
        for candidate in self.facts:
            if candidate.id == fact_id:
                return candidate
        raise KeyError(f"no planted fact {fact_id!r}")


def default_facts(pages: int) -> list[PlantedFact]:
    """Three facts: early, middle, and near the end.

    The placement is the point. A cap that reads a prefix of the document
    recovers the early fact and misses the late one, so a run that reports
    success on ALPHA alone is a partial read reporting as a complete one.
    """
    return [
        PlantedFact(
            id="NEEDLE-ALPHA",
            page=max(1, pages // 10),
            sentence="the anomalous reading was 47.3 microsieverts, recorded at station K-9",
            question="What anomalous reading was recorded, and at which station?",
            expected="47.3 microsieverts at station K-9",
        ),
        PlantedFact(
            id="NEEDLE-BETA",
            page=max(2, (2 * pages) // 3),
            sentence="the contract penalty clause caps total liability at 2,150,000 EUR",
            question="What is the cap on total liability under the penalty clause?",
            expected="2,150,000 EUR",
        ),
        PlantedFact(
            id="NEEDLE-GAMMA",
            page=max(3, pages - 2),
            sentence="the decommission date was moved from 2029-11-02 to 2031-04-18",
            question="What is the decommission date, and what was it before it moved?",
            expected="moved from 2029-11-02 to 2031-04-18",
        ),
    ]


def _page_lines(page: int, pages: int, facts: list[PlantedFact]) -> list[str]:
    lines = [
        f"Section {page // 10 + 1}: Operational Report",
        f"Page {page} of {pages}",
        "",
    ]
    lines += [f"Line {index:02d}. Routine operational detail for this reporting period; no exceptions were logged." for index in range(_LINES_PER_PAGE)]
    for fact in facts:
        if fact.page == page:
            lines.append("")
            lines.append(f"{fact.marker} {fact.sentence}.")
    return lines


def build_corpus(out_dir: Path, *, pages: int = 300, facts: list[PlantedFact] | None = None) -> Corpus:
    """Write a ``pages``-page PDF plus its manifest into *out_dir*.

    Raises ImportError with an actionable message when pymupdf is absent —
    generating the corpus is the one step that genuinely needs it, and a
    stack trace about a missing module would send the reader to the wrong place.
    """
    try:
        import pymupdf
    except ImportError as exc:  # pragma: no cover - environment-dependent
        raise ImportError("pymupdf is required to generate the drift-eval corpus; it ships with the backend's pymupdf4llm dependency (`uv sync`).") from exc

    planted = facts if facts is not None else default_facts(pages)
    out_dir.mkdir(parents=True, exist_ok=True)
    pdf_path = out_dir / f"synthetic-report-{pages}p.pdf"

    document = pymupdf.open()
    for page_number in range(1, pages + 1):
        page = document.new_page()
        body = [SYNTHETIC_BANNER, ""] + _page_lines(page_number, pages, planted)
        page.insert_text((40, 50), "\n".join(body), fontsize=8)
    document.save(str(pdf_path))
    document.close()

    manifest_path = out_dir / f"{pdf_path.stem}.manifest.json"
    manifest_path.write_text(
        json.dumps(
            {
                "synthetic": True,
                "generator": "deer-flow scripts.benchmark.drift_eval.corpus",
                "banner": SYNTHETIC_BANNER,
                "pdf": pdf_path.name,
                "pages": pages,
                "facts": [asdict(fact) for fact in planted],
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    return Corpus(pdf_path=pdf_path, manifest_path=manifest_path, pages=pages, facts=planted)


def load_corpus(manifest_path: Path) -> Corpus:
    """Rehydrate a corpus from a manifest written by :func:`build_corpus`."""
    data = json.loads(manifest_path.read_text(encoding="utf-8"))
    return Corpus(
        pdf_path=manifest_path.parent / data["pdf"],
        manifest_path=manifest_path,
        pages=int(data["pages"]),
        facts=[PlantedFact(**entry) for entry in data["facts"]],
    )
